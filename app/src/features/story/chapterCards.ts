const cardsBySlug = new Map(
  [...Object.values(storyCards).flat(), ...chapterPrintings].map(card => [card.slug, card]),
);

export function getChapterCards(slug: string): StoryCard[] {
  return (chapterCardSlugs[slug] ?? []).flatMap(cardSlug => {
    const card = cardsBySlug.get(cardSlug);
    if (!card) return [];
    const caption = chapterCaptions[slug]?.[cardSlug];
    return [caption ? { ...card, caption } : card];
  });
}
