/** Rebuild direct match consumers, preserving unrelated deck grouping and similarity artifacts. */
import {readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {writeJsonAtomic} from '../src/lib/atomicWrite.js';
import {createAnalysisContext} from '../src/analysis/context.js';
import {buildCardIndex} from '../src/cards/catalog.js';
import {computeEloRatings} from '../src/analysis/elo.js';
import {computeRivals} from '../src/analysis/rivals.js';
import {computeArchetypeAnalysis} from '../src/analysis/archetypes.js';
import {computeFieldHistory} from '../src/analysis/fieldHistory.js';
import {computeMatchupCardImpact} from '../src/analysis/matchupCardImpact.js';
import {computeBudgetDecks} from '../src/analysis/budgetDecks.js';
import {computeAchievements} from '../src/analysis/achievements.js';
import {writeRegionalStrength} from '../src/analysis/regionalStrength.js';
import {writeCompetitionReports} from '../src/analysis/competitionReports.js';
import {config} from '../src/config.js';
import type {OmnidexEventBundle} from '../src/omnidex/cache.js';
const root=new URL('../../data/',import.meta.url);
const read=async(file:string)=>JSON.parse(await readFile(new URL(file,root),'utf8'));
const directory=fileURLToPath(new URL('analysis/',root));
const index=await read('omnidex/index.json');const bundles:OmnidexEventBundle[]=[];
for(const event of index.events)if(event.status==='complete' && Date.parse(event.date)<=Date.parse(index.generatedAt))bundles.push(await read(`omnidex/events/${event.id}.json`));
const generatedAt=new Date().toISOString(), written=new Map<string,string>();
const save=async(name:string,key:string,data:unknown)=>{await writeJsonAtomic(`${directory}/${name}.json`,data,0);written.set(key,`analysis/${name}.json`);console.log(`Rebuilt ${name}`);};
const ctx=createAnalysisContext(buildCardIndex((await read('card-catalog.json')).cards));
const {ratings,upsets,history}=computeEloRatings(bundles);
const historyData={generatedAt,history:Object.fromEntries(history)};
await save('elo','analysis-elo',{generatedAt,ratings:[...ratings.values()].sort((a,b)=>b.rating-a.rating),upsets:upsets.sort((a,b)=>b.eventDate.localeCompare(a.eventDate))});
await save('elo-history','analysis-elo-history',historyData);
await save('rivals','analysis-rivals',{generatedAt,players:computeRivals(bundles)});
await writeRegionalStrength(directory,bundles,historyData);
written.set('regional-strength','analysis/regional-strength.json');written.set('player-comparison','analysis/player-comparison.json');
console.log('Rebuilt regional strength and player comparison');
await save('archetypes','analysis-archetypes',{generatedAt,...computeArchetypeAnalysis(bundles,ctx)});
await save('field-history','analysis-field-history',computeFieldHistory(bundles,ctx,config.minBattleChartSampleSize));
const taxonomy=await read('analysis/archetype-taxonomy.json');
await save('matchup-card-impact','analysis-matchup-card-impact',computeMatchupCardImpact(bundles,ctx,taxonomy.clusters));
await save('budget-decks','analysis-budget-decks',computeBudgetDecks(bundles,ctx,await read('prices.json'),generatedAt));
await save('achievements','analysis-achievements',computeAchievements(bundles,ctx,ratings,upsets,(await read('analysis/hipster.json')).deckScores,(await read('analysis/deck-sightings.json')).sightings));
await writeCompetitionReports(directory,bundles,ctx,(await read('analysis/deck-popularity-index.json')).entries,await read('analysis/deck-card-index.json'),taxonomy);
for(const name of ['seasons','battle','players','places','teams'])written.set(`competition-${name}`,`analysis/competition-${name}.json`);
const manifest=await read('manifest.json');
for(const [key,file] of written)manifest[key]=(await read(file)).generatedAt;
await writeJsonAtomic(fileURLToPath(new URL('manifest.json',root)),manifest,0);
console.log('Match analysis and manifest complete.');
